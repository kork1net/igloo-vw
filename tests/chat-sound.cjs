const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let now = 1000, plays = 0, stops = 0;
const document = { hidden: false };
const sound = { locked: false, context: { state: 'running' }, stopByKey() { stops++; }, play() { plays++; } };
const source = fs.readFileSync('src/game/ui/ChatSound.js', 'utf8').replaceAll('export function', 'function');
const { playChatSound, silenceChatSound } = vm.runInNewContext(source + '\n({playChatSound,silenceChatSound})', { document, performance: { now: () => now } });
const scene = { sound };
playChatSound(scene); assert.equal(plays, 1);
for (let i = 0; i < 20; i++) playChatSound(scene);
assert.equal(plays, 1, 'A burst cannot overlap chat sounds');
document.hidden = true; now += 1000;
for (let i = 0; i < 20; i++) playChatSound(scene);
assert.equal(plays, 1, 'Hidden messages never enqueue sounds');
document.hidden = false; sound.context.state = 'suspended'; now += 1000;
playChatSound(scene); assert.equal(plays, 1, 'Suspended audio does not queue notifications');
sound.context.state = 'running'; silenceChatSound(sound);
playChatSound(scene); assert.equal(plays, 1, 'Returning to tab suppresses an immediate notification burst');
now += 400; playChatSound(scene); assert.equal(plays, 2);
sound.locked = true; now += 1000; playChatSound(scene); assert.equal(plays, 2);
assert.equal(stops, 3);
console.log('PASS chat sound: background/suspended/locked suppression, no overlaps, return cooldown and normal recovery');
