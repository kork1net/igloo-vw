const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { Inventories } = require('../server/inventory.cjs');
const { buildCatalog } = require('../scripts/item-catalog.cjs');
const { chain } = require('../server/quests.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vw-quests-'));
try {
    const store = new Inventories(directory);
    const catalog = buildCatalog();
    const user = { id: 'quest-player', username: 'QuestPlayer' };
    const view = () => store.snapshot(user, catalog).quests[chain.id];
    const claim = index => store.claimQuest(user, chain.id, chain.steps[index].id, catalog);
    const initial = store.snapshot(user, catalog);
    assert.equal(view().started, false);
    assert.throws(() => claim(0));
    assert.throws(() => store.acceptQuest(user, '__proto__', catalog));
    store.acceptQuest(user, chain.id, catalog);
    const accepted = store.snapshot(user, catalog);
    store.acceptQuest(user, chain.id, catalog);
    assert.deepEqual(store.snapshot(user, catalog), accepted);
    assert.throws(() => claim(1));
    assert.throws(() => claim(0));
    assert.equal(view().steps[0].ready, false);
    store.purchase(user, 'shirt/black-shirt', catalog);
    assert.equal(view().steps[0].ready, true);
    claim(0);
    assert.equal(view().claimedSteps, 1);
    const first = store.snapshot(user, catalog);
    assert.throws(() => claim(0));
    assert.deepEqual(store.snapshot(user, catalog), first);
    assert.throws(() => claim(1));
    store.rewardSnow(user, { id: 'snow-finished', elapsed: 45000, score: 30, catches: 3 });
    assert.equal(view().steps[1].ready, false);
    store.rewardSnow(user, { id: 'snow-old-record', elapsed: 45000, score: 1000, catches: 40 });
    assert.equal(view().steps[1].ready, false);
    assert.equal(store.snapshot(user, catalog).snowBest, 1000);
    store.rewardSnow(user, { id: 'snow-200', elapsed: 45000, score: 200, catches: 20, questStepId: 'snow-catch' });
    assert.equal(view().steps[1].ready, true);
    claim(1);
    assert.equal(view().claimedSteps, 2);
    assert.equal(view().steps[2].ready, false);
    store.rewardSnow(user, { id: 'snow-200', elapsed: 45000, score: 1000, catches: 40, questStepId: 'snow-champion' });
    assert.equal(view().steps[2].ready, false);
    assert.throws(() => claim(2));
    store.rewardSnow(user, { id: 'previous-stage-round', elapsed: 45000, score: 800, catches: 40, questStepId: 'snow-catch' });
    assert.equal(view().steps[2].ready, false);
    store.rewardSnow(user, { id: 'snow-400', elapsed: 45000, score: 400, catches: 40, questStepId: 'snow-champion' });
    assert.equal(view().steps[2].ready, true);
    assert.equal(store.snapshot(user, catalog).snowBest, 1000);
    claim(2);
    assert.throws(() => claim(2));
    assert.equal(view().claimedSteps, 3);
    store.purchase(user, 'pants/blue-jeans', catalog);
    assert.equal(view().steps[3].ready, false);
    store.equip(user, 'shirt/black-shirt', true, catalog);
    assert.equal(view().steps[3].ready, true);
    const before = store.snapshot(user, catalog);
    const persist = store.persist;
    store.persist = () => { throw new Error('disk failure'); };
    assert.throws(() => claim(3), /disk failure/);
    assert.deepEqual(store.snapshot(user, catalog), before);
    store.persist = persist;
    claim(3);
    const complete = store.snapshot(user, catalog);
    assert.equal(complete.quests[chain.id].completed, true);
    assert.equal(complete.currency, before.currency + chain.steps[3].coins);
    assert.equal(complete.rankingPoints, before.rankingPoints + chain.steps[3].rankingPoints);
    assert.ok(complete.items.includes('accessory/black-sun-glasses'));
    assert.equal(complete.equipped.shirt, 'shirt/black-shirt');
    assert.throws(() => claim(3));
    assert.deepEqual(store.snapshot(user, catalog), complete);
    assert.deepEqual(new Inventories(directory).snapshot(user, catalog), complete);
    assert.equal(complete.items.filter(id => id === chain.steps[3].itemReward).length, 1);
    assert.ok(complete.rankingPoints > initial.rankingPoints);
    const admin = { id: 'quest-admin', username: 'Admin', isAdmin: true };
    store.acceptQuest(admin, chain.id, catalog);
    assert.equal(store.snapshot(admin, catalog).quests[chain.id].steps[0].ready, true);
    store.claimQuest(admin, chain.id, chain.steps[0].id, catalog);
    const giftUser = { id: 'gift-user', username: 'Gift' };
    const gifted = store.load(giftUser);
    store.persist(giftUser, { ...gifted, items: [...gifted.items, 'shirt/black-shirt'] });
    store.acceptQuest(giftUser, chain.id, catalog);
    assert.equal(store.snapshot(giftUser, catalog).quests[chain.id].steps[0].ready, false);
    const legacyUser = { id: 'legacy-user', username: 'Legacy' };
    const legacy = store.load(legacyUser);
    delete legacy.purchasedItems;
    store.persist(legacyUser, { ...legacy, items: [...legacy.items, 'shirt/black-shirt'] });
    store.acceptQuest(legacyUser, chain.id, catalog);
    assert.equal(store.snapshot(legacyUser, catalog).quests[chain.id].steps[0].ready, true);
    // Old completed chains must never pay the final prize again after insertion.
    const oldCompleted = store.load(legacyUser);
    store.persist(legacyUser, { ...oldCompleted, quests: { [chain.id]: { started: true, claimed: 3 } } });
    const legacyComplete = store.snapshot(legacyUser, catalog);
    assert.equal(legacyComplete.quests[chain.id].completed, true);
    assert.throws(() => store.claimQuest(legacyUser, chain.id, 'ready-for-igloo', catalog));
    assert.deepEqual(store.snapshot(legacyUser, catalog), legacyComplete);
    store.persist(legacyUser, { ...oldCompleted, quests: { [chain.id]: { started: true, claimed: 2 } } });
    const migrating = store.snapshot(legacyUser, catalog).quests[chain.id];
    assert.equal(migrating.steps[migrating.claimedSteps].id, 'snow-champion');
    assert.ok(migrating.claimedIds.includes('snow-catch'));
} finally {
    const resolved = fs.realpathSync(directory);
    assert.equal(path.dirname(resolved).toLowerCase(), fs.realpathSync(os.tmpdir()).toLowerCase());
    assert.ok(path.basename(resolved).startsWith('vw-quests-'));
    fs.rmSync(resolved, { recursive: true });
}
console.log('PASS: ordered chain, purchase/snow/outfit checks, per-step rewards, final glasses, duplicate claims, persistence, rollback, admins and legacy players');
