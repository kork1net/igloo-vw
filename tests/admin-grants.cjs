const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { Inventories } = require('../server/inventory.cjs');
const { buildCatalog } = require('../scripts/item-catalog.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vw-admin-grants-'));
try {
    const store = new Inventories(directory), catalog = buildCatalog();
    const recipient = { id: 'recipient', username: 'Player' };
    const admin = { id: 'admin', username: 'Koko', isAdmin: true };
    const request = { id: 'gift-test-001', kind: 'currency', amount: 25 };
    const initial = store.snapshot(recipient, catalog);
    assert.throws(() => store.grant(recipient, recipient, request));
    for (const amount of [0, -1, 1.5, '25', NaN, Infinity, 1000001]) assert.throws(() => store.grant(recipient, admin, { ...request, amount }));
    assert.throws(() => store.grant(recipient, admin, { ...request, kind: 'level' }));
    const gift = store.grant(recipient, admin, request);
    assert.equal(gift.senderName, 'Koko');
    assert.equal(store.snapshot(recipient, catalog).currency, initial.currency + 25);
    assert.equal(store.snapshot(recipient, catalog).adminGifts.length, 1);
    store.grant(recipient, admin, request);
    assert.equal(store.snapshot(recipient, catalog).currency, initial.currency + 25);
    assert.throws(() => store.grant(recipient, admin, { ...request, amount: 30 }));
    assert.throws(() => store.acknowledgeGift({ id: 'other' }, gift.id, admin.id));
    const restored = new Inventories(directory);
    assert.equal(restored.snapshot(recipient, catalog).adminGifts[0].amount, 25);
    restored.acknowledgeGift(recipient, gift.id, admin.id);
    restored.acknowledgeGift(recipient, gift.id, admin.id);
    restored.grant(recipient, admin, request);
    assert.equal(restored.snapshot(recipient, catalog).adminGifts.length, 0);
    assert.equal(restored.snapshot(recipient, catalog).currency, initial.currency + 25);
    restored.grant(recipient, admin, { id: 'gift-test-002', kind: 'rankingPoints', amount: 260 });
    assert.equal(restored.snapshot(recipient, catalog).level, 3);
    assert.equal(restored.snapshot(recipient, catalog).rankingPoints, 260);
    const beforeFailure = restored.snapshot(recipient, catalog);
    const rename = fs.renameSync;
    try {
        fs.renameSync = () => { throw new Error('Test write failure'); };
        assert.throws(() => restored.grant(recipient, admin, { ...request, id: 'gift-failure-001' }));
    } finally { fs.renameSync = rename; }
    assert.deepEqual(restored.snapshot(recipient, catalog), beforeFailure);
    const both = { id: 'gift-both-001', kind: 'both', amount: 12, rankingAmount: 35 };
    assert.throws(() => restored.grant(recipient, admin, { ...both, rankingAmount: 0 }));
    assert.throws(() => restored.grant(recipient, admin, { ...both, rankingAmount: 1.5 }));
    restored.grant(recipient, admin, both);
    restored.grant(recipient, admin, both);
    assert.equal(restored.snapshot(recipient, catalog).currency, beforeFailure.currency + 12);
    assert.equal(restored.snapshot(recipient, catalog).rankingPoints, beforeFailure.rankingPoints + 35);
    const firstMember = { id: 'member1', username: 'Member1' };
    const secondMember = { id: 'member2', username: 'Member2' };
    const newcomer = { id: 'member3', username: 'Member3' };
    const batch = { id: 'batch-both-001', kind: 'both', amount: 11, rankingAmount: 13 };
    assert.throws(() => restored.grantRoom(recipient, 'Game', batch, [firstMember]));
    assert.equal(restored.grantRoom(admin, 'Game', batch, [firstMember, firstMember, secondMember]), 2);
    const restart = new Inventories(directory);
    assert.equal(restart.grantRoom(admin, 'Game', batch, [firstMember, newcomer]), 2);
    assert.equal(restart.snapshot(firstMember, catalog).currency, initial.currency + 11);
    assert.equal(restart.snapshot(secondMember, catalog).rankingPoints, 13);
    assert.equal(restart.snapshot(newcomer, catalog).rankingPoints, 0);
    assert.throws(() => restart.grantRoom(admin, 'Cafe', batch, [firstMember]));
    assert.throws(() => restart.grantRoom(admin, 'Game', { ...batch, rankingAmount: 14 }, [firstMember]));
    const retry = { ...batch, id: 'batch-retry-001' };
    assert.throws(() => restart.grantRoom(admin, 'Game', retry, [firstMember, secondMember], () => { throw Error('Notification failed'); }));
    restart.grantRoom(admin, 'Game', retry, [newcomer]);
    assert.equal(restart.snapshot(firstMember, catalog).currency, initial.currency + 22);
    assert.equal(restart.snapshot(secondMember, catalog).currency, initial.currency + 22);
    console.log('PASS: admin grants, validation, duplicate protection after acknowledgement, offline notices, progression, persistence and atomic rollback');
    console.log('PASS: combined gifts, unique room members, persisted recipient list, late joiners and partial batch retries');
} finally {
    const resolved = fs.realpathSync(directory);
    assert.equal(path.dirname(resolved).toLowerCase(), fs.realpathSync(os.tmpdir()).toLowerCase());
    assert.ok(path.basename(resolved).startsWith('vw-admin-grants-'));
    fs.rmSync(resolved, { recursive: true });
}
